const STEPS = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900];

export const BRAND_COLOURS = Object.keys(hex).map((name) => ({ name, label: name[0].toUpperCase() + name.slice(1), swatch: hex[name][6] }));

const toRgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16)).join(' ');

export function applyBrandColour(name) {
  const shades = hex[name] || hex.indigo;
  const root = document.documentElement;
  STEPS.forEach((step, i) => root.style.setProperty(`--brand-${step}`, toRgb(shades[i])));
}
